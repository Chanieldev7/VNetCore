// Self-hosts the IBM Plex fonts so the app makes no third-party requests.
// Copies only the Latin and Latin Extended woff2 files that the UI uses and
// writes assets/fonts.css with matching @font-face rules and unicode ranges.
const fs = require("node:fs/promises");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const outDir = path.join(root, "assets", "fonts");
const families = [
  { pkg: "ibm-plex-sans", weights: [400, 500, 600, 700] },
  { pkg: "ibm-plex-mono", weights: [400, 500, 600] },
];
const subsets = ["latin", "latin-ext"];

async function main() {
  await fs.rm(outDir, { recursive: true, force: true });
  await fs.mkdir(outDir, { recursive: true });
  const rules = ["/* Generated by scripts/build-fonts.cjs. Do not edit. */"];
  for (const { pkg, weights } of families) {
    const pkgDir = path.join(root, "node_modules", "@fontsource", pkg);
    await fs.copyFile(path.join(pkgDir, "LICENSE"), path.join(outDir, `${pkg}-LICENSE.txt`));
    for (const weight of weights) {
      // The per-weight CSS carries the unicode-range for every subset.
      const css = await fs.readFile(path.join(pkgDir, `${weight}.css`), "utf8");
      for (const subset of subsets) {
        const file = `${pkg}-${subset}-${weight}-normal.woff2`;
        const block = css.match(
          new RegExp(`/\\* ${pkg}-${subset}-${weight}-normal \\*/\\s*(@font-face\\s*{[^}]*})`),
        )?.slice(1);
        if (!block || !block[0].includes("unicode-range")) {
          throw new Error(`No @font-face with unicode-range for ${pkg} ${subset} ${weight}.`);
        }
        await fs.copyFile(path.join(pkgDir, "files", file), path.join(outDir, file));
        // Keep woff2 only: every target browser supports it.
        rules.push(block[0].replace(/src:[^;]*;/, `src: url(fonts/${file}) format("woff2");`));
      }
    }
  }
  await fs.writeFile(path.join(root, "assets", "fonts.css"), `${rules.join("\n\n")}\n`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
